// 一項攤平成組：字串也當成只有一個名稱的組，前端不用分兩種情況
export function groupsFor(theme, lang) {
  return NAMES[theme][lang].map((item) => (Array.isArray(item) ? item : [item]));
}

/*
 * build 時擋下來的東西：
 * - 主題少了某個語言的清單（那個語言的取名畫面會是空的）
 * - 同一個主題裡名稱重複（同一局可能抽到兩個一樣的）
 * - 太長（喊不快）
 * - 組數太少（20 個人抽不完）
 */
export function checkNames(langs) {
  for (const theme of THEMES) {
    for (const lang of langs) {
      const list = NAMES[theme]?.[lang];
      if (!list) throw new Error(`names.js：主題 ${theme} 少了 ${lang} 的清單`);

      const groups = groupsFor(theme, lang);
      if (groups.length < MIN_GROUPS) {
        throw new Error(`names.js：${theme}／${lang} 只有 ${groups.length} 組，至少要 ${MIN_GROUPS} 組`);
      }

      const seen = new Set();
      for (const name of groups.flat()) {
        if (seen.has(name)) throw new Error(`names.js：${theme}／${lang} 的「${name}」重複了`);
        seen.add(name);
        if ([...name].length > NAME_MAX) {
          throw new Error(`names.js：${theme}／${lang} 的「${name}」超過 ${NAME_MAX} 個字`);
        }
      }
    }
  }
}
