export function checkSlot(langs) {
  for (const lang of langs) {
    const s = SLOT[lang];
    if (!s) throw new Error(`slot-prompts.mjs 少了 ${lang}`);
    if (s.prompts.length < 30) throw new Error(`slot-prompts.mjs：${lang} 的真心話只有 ${s.prompts.length} 題，至少要 30 題`);
    if (s.actions.length < 15) throw new Error(`slot-prompts.mjs：${lang} 的大冒險只有 ${s.actions.length} 個，至少要 15 個`);
  }
}
