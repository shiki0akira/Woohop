export const actionsFor = (lang) => ACTIONS[lang] || ACTIONS['zh-TW'];

// artSource：woohop-art.js 的內容（插圖代號是 actionArt 裡的 `    代號: function`）
export function checkActions(artSource) {
  const art = new Set([...artSource.matchAll(/^    (\w+): function \(c\)/gm)].map((m) => m[1]));
  const ref = ACTIONS['zh-TW'].map(([k]) => k).join();
  for (const [lang, list] of Object.entries(ACTIONS)) {
    if (list.map(([k]) => k).join() !== ref) throw new Error(`action-cards：${lang} 的動作代號跟 zh-TW 不一樣`);
    for (const [key, name] of list) if (!art.has(key)) throw new Error(`action-cards：${lang} 的「${name}」沒有插圖（woohop-art.js 的 actionArt 少了 ${key}）`);
  }
}
